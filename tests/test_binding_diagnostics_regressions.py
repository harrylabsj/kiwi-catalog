"""Binding denial diagnostics and state side effects, using isolated ASGI/SQLite.

Supplement the existing diagnostic tests with challenge response branches,
log-injection boundaries and nonce/enrollment invariants. External challenge
POSTs are mocked; keys and grants are generated by the existing test fixture.
"""

from __future__ import annotations

import json
import time
from datetime import UTC, datetime, timedelta
from unittest import mock

from kiwi_catalog.api.handlers import cloud_binding
from kiwi_catalog.core.errors import PermissionDenied
from kiwi_catalog.db.session import db_session
from kiwi_catalog.discovery.fetcher import FetchResult, ProfileFetcher

from tests import test_binding_diagnostics as diagnostics
from tests.test_cloud_binding import _call
from tests.test_enrollment_security import RUNTIME_ORIGIN, EnrollmentFixture

_LOG_NAME = "kiwi_catalog.api.handlers.cloud_binding"


class BindingDiagnosticsRegressionsTest(EnrollmentFixture):
    def _ready(self, **binding_overrides):
        enrollment_id = "enr_diagnostic_regression"
        _, device_hash = self._insert_enrollment(enrollment_id=enrollment_id)
        grant = diagnostics.cloud_binding_enrollment_grant(enrollment_id, device_hash)
        body, signature = diagnostics.EnrollmentBindDenialDiagnosticsTest._signed_bind_body(
            self, enrollment_id, grant, **binding_overrides,
        )
        return body, signature

    def _enrollment_state(self, enrollment_id):
        with db_session(self.db_path) as conn:
            row = conn.execute(
                "select status,binding_id,expected_binding_version,consumed_at from enrollments where enrollment_id=?",
                (enrollment_id,),
            ).fetchone()
            bindings = conn.execute(
                "select count(*) from runtime_bindings where catalog_agent_id=?", (self.agent_id,),
            ).fetchone()[0]
        return tuple(row), bindings

    def _nonces(self):
        with db_session(self.db_path) as conn:
            return [tuple(row) for row in conn.execute(
                "select key_id,nonce,issued_at,expires_at,created_at from control_plane_nonces order by key_id,nonce",
            )]

    def _assert_safe_diagnostic(self, captured, code, stage, *, grant, signature):
        messages = [record.getMessage() for record in captured.records]
        self.assertEqual(len(messages), 1)
        message = messages[0]
        self.assertIn(f"code={code} stage={stage} agent={self.agent_id}", message)
        self.assertTrue("\r" not in message and "\n" not in message, "diagnostic must remain one line")
        self.assertTrue(grant not in message, "diagnostic leaked test grant")
        self.assertTrue(signature not in message, "diagnostic leaked test JWS")
        self.assertTrue(self.private_pem not in message, "diagnostic leaked test private key")
        self.assertTrue("grant=" not in message and "nonce=" not in message)

    def _assert_challenge_denial(self, response_body, code, error):
        body, signature = self._ready()
        before = self._enrollment_state(body["enrollment_id"])
        initial_nonces = self._nonces()

        def respond(url, payload, *, timeout):
            self.assertEqual(url, RUNTIME_ORIGIN + "/.well-known/kiwi-binding-challenge")
            self.assertEqual(timeout, 5)
            text = response_body(payload, body["grant"], signature)
            return FetchResult(url=url, status_code=200, body=text, fetched_at=time.time())

        with mock.patch.object(ProfileFetcher, "post_json", side_effect=respond) as challenge:
            with self.assertLogs(_LOG_NAME, level="WARNING") as captured:
                status, result = _call(
                    self.app, "POST", f"/v1/agents/{self.agent_id}/runtime-bindings", body, signature=signature,
                )
        self.assertEqual(status, 403)
        self.assertEqual(result, {"ok": False, "error": error})
        challenge.assert_called_once()
        self._assert_safe_diagnostic(captured, code, "challenge_response", grant=body["grant"], signature=signature)
        # A valid possession consumes exactly its request nonce, but a rejected
        # challenge must not create a binding or consume the enrollment grant.
        self.assertEqual(self._enrollment_state(body["enrollment_id"]), before)
        nonces = self._nonces()
        self.assertEqual(len(nonces), len(initial_nonces) + 1)
        self.assertTrue(any(row[1] == diagnostics._jws_nonce(signature) for row in nonces))

    def test_challenge_invalid_json_preserves_authorization_and_has_safe_diagnostic(self):
        self._assert_challenge_denial(
            lambda _payload, grant, signature: f"<<not-json:{grant}:{signature}>>",
            "BIND_CHALLENGE_INVALID_JSON", "runtime endpoint challenge returned invalid JSON",
        )

    def test_challenge_invalid_shape_preserves_authorization_and_has_safe_diagnostic(self):
        self._assert_challenge_denial(
            lambda _payload, grant, signature: json.dumps({"unexpected": grant, "signature": signature}),
            "BIND_CHALLENGE_INVALID_SHAPE", "runtime endpoint challenge response shape is invalid",
        )

    def test_challenge_response_mismatch_preserves_authorization_and_has_safe_diagnostic(self):
        self._assert_challenge_denial(
            lambda payload, _grant, signature: json.dumps({
                **payload, "origin": "https://wrong.example", "key_id": RUNTIME_ORIGIN, "signature": signature,
            }),
            "BIND_CHALLENGE_RESPONSE_MISMATCH", "runtime endpoint challenge response mismatch",
        )

    def test_binding_key_mismatch_does_not_consume_nonce_or_contact_runtime(self):
        body, signature = self._ready(key_id="different-key-id")
        before = self._enrollment_state(body["enrollment_id"])
        initial_nonces = self._nonces()
        with mock.patch.object(ProfileFetcher, "post_json") as challenge:
            with self.assertLogs(_LOG_NAME, level="WARNING") as captured:
                status, result = _call(
                    self.app, "POST", f"/v1/agents/{self.agent_id}/runtime-bindings", body, signature=signature,
                )
        self.assertEqual(status, 403)
        self.assertEqual(result, {"ok": False, "error": "binding key does not match approved enrollment"})
        challenge.assert_not_called()
        self.assertEqual(self._nonces(), initial_nonces)
        self.assertEqual(self._enrollment_state(body["enrollment_id"]), before)
        self._assert_safe_diagnostic(captured, "BIND_KEY_MISMATCH", "validate_key",
                                     grant=body["grant"], signature=signature)

    def test_log_identifier_cannot_inject_newline_or_forged_fields_or_exception_secrets(self):
        body, signature = self._ready()
        hostile_id = "cagt_ok\r\ncode=FORGED stage=FORGED agent=cagt_forged"
        with self.assertLogs(_LOG_NAME, level="WARNING") as captured:
            with self.assertRaises(PermissionDenied):
                cloud_binding._deny(
                    "BIND_MATERIAL_MISMATCH", "validate_material", hostile_id, "safe fixed error",
                    cause=ValueError(body["grant"] + signature),
                )
        self.assertEqual(len(captured.records), 1)
        message = captured.records[0].getMessage()
        self.assertEqual(message.count(" code="), 1)
        self.assertEqual(message.count(" stage="), 1)
        self.assertEqual(message.count(" agent="), 1)
        self.assertTrue("\r" not in message and "\n" not in message)
        self.assertIn(r"\x0d\x0acode\x3dFORGED\x20stage\x3dFORGED\x20agent\x3dcagt_forged", message)
        self.assertTrue(body["grant"] not in message, "diagnostic leaked test grant")
        self.assertTrue(signature not in message, "diagnostic leaked test JWS")
        self.assertIsNone(captured.records[0].exc_info)

    def test_invalid_possession_leaves_nonce_store_and_authorization_unchanged(self):
        _, grant, body, signature_for = diagnostics.PossessionAndBoundaryDiagnosticsTest._ready_bind(self)
        valid = signature_for()
        segment_start = valid.rindex(".") + 1
        position = segment_start + (len(valid) - segment_start) // 2
        replacement = "A" if valid[position] != "A" else "B"
        tampered = valid[:position] + replacement + valid[position + 1:]
        before = self._enrollment_state(body["enrollment_id"])
        initial_nonces = self._nonces()
        for signature in (signature_for(path="/v1/agents/someone-else/runtime-bindings"), tampered):
            with self.subTest(proof="wrong-path" if signature != tampered else "invalid-signature"):
                with mock.patch.object(ProfileFetcher, "post_json") as challenge:
                    with self.assertLogs(_LOG_NAME, level="WARNING") as captured:
                        status, _result = _call(
                            self.app, "POST", f"/v1/agents/{self.agent_id}/runtime-bindings", body,
                            signature=signature,
                        )
                self.assertEqual(status, 403)
                challenge.assert_not_called()
                self.assertEqual(self._nonces(), initial_nonces)
                self.assertEqual(self._enrollment_state(body["enrollment_id"]), before)
                self._assert_safe_diagnostic(captured, "BIND_POSSESSION_INVALID", "validate_possession",
                                             grant=grant, signature=signature)

    def test_nonce_replay_preserves_existing_row_count_and_authorization(self):
        body, signature = self._ready()
        now = datetime.now(UTC).replace(microsecond=0)
        with db_session(self.db_path) as conn:
            conn.execute(
                "insert into control_plane_nonces(key_id,nonce,issued_at,expires_at,created_at) values(?,?,?,?,?)",
                (RUNTIME_ORIGIN, diagnostics._jws_nonce(signature), now.isoformat(),
                 (now + timedelta(minutes=5)).isoformat(), now.isoformat()),
            )
        initial_nonces = self._nonces()
        before = self._enrollment_state(body["enrollment_id"])
        with mock.patch.object(ProfileFetcher, "post_json") as challenge:
            with self.assertLogs(_LOG_NAME, level="WARNING") as captured:
                status, result = _call(
                    self.app, "POST", f"/v1/agents/{self.agent_id}/runtime-bindings", body, signature=signature,
                )
        self.assertEqual(status, 403)
        self.assertEqual(result, {"ok": False, "error": "request signature replayed (nonce already used)"})
        challenge.assert_not_called()
        self.assertEqual(len(self._nonces()), 1)
        self.assertEqual(self._nonces(), initial_nonces)
        self.assertEqual(self._enrollment_state(body["enrollment_id"]), before)
        self._assert_safe_diagnostic(captured, "BIND_POSSESSION_REPLAY", "validate_possession",
                                     grant=body["grant"], signature=signature)
